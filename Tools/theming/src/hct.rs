//! CAM16 and the hue-preserving HCT gamut solver.
//! Port of the theme engine's Material Color Utilities implementation.
use crate::color::Rgb;
use std::f64::consts::PI;

const N: f64 = 0.18418651851244416;
const AW: f64 = 29.980997194447333;
const NBB: f64 = 1.0169191804458755;
const C: f64 = 0.69;
const FL: f64 = 0.3884814537800353;
const Z: f64 = 1.909169568483652;
const RGB_D: [f64; 3] = [1.0211931250282205, 0.9862992588498498, 0.9338046048498166];
const SRGB_TO_XYZ: [[f64; 3]; 3] = [
    [0.41233895, 0.35762064, 0.18051042],
    [0.2126, 0.7152, 0.0722],
    [0.01932141, 0.11916382, 0.95034478],
];
const DISCOUNT: [[f64; 3]; 3] = [
    [
        0.001200833568784504,
        0.002389694492170889,
        0.0002795742885861124,
    ],
    [
        0.0005891086651375999,
        0.0029785502573438758,
        0.0003270666104008398,
    ],
    [
        0.00010146692491640572,
        0.0005364214359186694,
        0.0032979401770712076,
    ],
];
const INVERSE_DISCOUNT: [[f64; 3]; 3] = [
    [1373.2198709594231, -1100.4251190754821, -7.278681089101213],
    [-271.815969077903, 559.6580465940733, -32.46047482791194],
    [1.9622899599665666, -57.173814538844006, 308.7233197812385],
];
const Y_COEFF: [f64; 3] = [0.2126, 0.7152, 0.0722];
fn multiply(m: [[f64; 3]; 3], v: [f64; 3]) -> [f64; 3] {
    m.map(|r| r[0] * v[0] + r[1] * v[1] + r[2] * v[2])
}
fn signum(x: f64) -> f64 {
    if x < 0.0 {
        -1.0
    } else if x > 0.0 {
        1.0
    } else {
        0.0
    }
}
fn linearize(c: u8) -> f64 {
    let c = c as f64 / 255.0;
    if c <= 0.040449936 {
        c / 12.92
    } else {
        ((c + 0.055) / 1.055).powf(2.4)
    }
}
fn delinearize(c: f64) -> u8 {
    let v = if c <= 0.0031308 {
        c * 12.92
    } else {
        1.055 * c.powf(1.0 / 2.4) - 0.055
    };
    (v * 255.0).round_ties_even().clamp(0.0, 255.0) as u8
}
fn rgb_to_xyz(rgb: Rgb) -> [f64; 3] {
    multiply(SRGB_TO_XYZ, rgb.map(linearize)).map(|v| v * 100.0)
}
fn y_to_lstar(y: f64) -> f64 {
    if y <= 0.0 {
        return 0.0;
    }
    let y = y / 100.0;
    if y <= 0.008856 {
        903.2962962962963 * y
    } else {
        116.0 * y.powf(1.0 / 3.0) - 16.0
    }
}
fn lstar_to_y(t: f64) -> f64 {
    if t <= 0.0 {
        return 0.0;
    }
    let t = t.min(100.0);
    if t <= 8.0 {
        t / 903.2962962962963 * 100.0
    } else {
        let f = (t + 16.0) / 116.0;
        f * f * f * 100.0
    }
}
#[derive(Clone, Copy, Debug)]
pub struct Cam16 {
    pub hue: f64,
    pub chroma: f64,
}
impl Cam16 {
    pub fn from_rgb(rgb: Rgb) -> Self {
        let [x, y, z] = rgb_to_xyz(rgb);
        let channels = [
            0.401288 * x + 0.650173 * y - 0.051461 * z,
            -0.250268 * x + 1.204414 * y + 0.045854 * z,
            -0.002079 * x + 0.048952 * y + 0.953127 * z,
        ];
        let mut adapted = [0.0; 3];
        for i in 0..3 {
            let d = RGB_D[i] * channels[i];
            let f = (FL * d.abs() / 100.0).powf(0.42);
            adapted[i] = signum(d) * 400.0 * f / (f + 27.13);
        }
        let [r, g, b] = adapted;
        let a = (11.0 * r + -12.0 * g + b) / 11.0;
        let b = (r + g - 2.0 * b) / 9.0;
        let radians = b.atan2(a);
        let mut hue = radians.to_degrees();
        if hue < 0.0 {
            hue += 360.0;
        }
        let u = (20.0 * r + 20.0 * g + 21.0 * adapted[2]) / 20.0;
        let p2 = (40.0 * r + 20.0 * g + adapted[2]) / 20.0;
        let ac = p2 * NBB;
        let j = 100.0 * (ac / AW).powf(C * Z);
        let hue_prime = if hue < 20.14 { hue + 360.0 } else { hue };
        let e = 0.25 * ((hue_prime.to_radians() + 2.0).cos() + 3.8);
        let t = 50000.0 / 13.0 * NBB * e * (a * a + b * b).sqrt() / (u + 0.305);
        let alpha = t.powf(0.9) * (1.64 - 0.29_f64.powf(N)).powf(0.73);
        Self {
            hue,
            chroma: alpha * (j / 100.0).sqrt(),
        }
    }
}
#[derive(Clone, Copy, Debug)]
pub struct Hct {
    pub hue: f64,
    pub chroma: f64,
    pub tone: f64,
}
impl Hct {
    pub fn from_rgb(rgb: Rgb) -> Self {
        let cam = Cam16::from_rgb(rgb);
        Self::from_hct(cam.hue, cam.chroma, y_to_lstar(rgb_to_xyz(rgb)[1]))
    }
    pub fn from_hct(hue: f64, chroma: f64, tone: f64) -> Self {
        Self {
            hue: hue.rem_euclid(360.0),
            chroma: chroma.max(0.0),
            tone: tone.clamp(0.0, 100.0),
        }
    }
    pub fn to_rgb(self) -> Rgb {
        solve(self.hue, self.chroma, self.tone)
    }
}
fn sanitize_radians(angle: f64) -> f64 {
    (angle + PI * 8.0).rem_euclid(PI * 2.0)
}
fn cyclic(a: f64, b: f64, c: f64) -> bool {
    sanitize_radians(b - a) < sanitize_radians(c - a)
}
fn adapt(c: f64) -> f64 {
    let a = c.abs().powf(0.42);
    signum(c) * 400.0 * a / (a + 27.13)
}
fn inverse_adapt(c: f64) -> f64 {
    let a = c.abs();
    let base = (27.13 * a / (400.0 - a)).max(0.0);
    signum(c) * base.powf(1.0 / 0.42)
}
fn hue_of(rgb: [f64; 3]) -> f64 {
    let [r, g, b] = multiply(DISCOUNT, rgb).map(adapt);
    let a = (11.0 * r - 12.0 * g + b) / 11.0;
    let b = (r + g - 2.0 * b) / 9.0;
    b.atan2(a)
}
fn vertex(y: f64, n: usize) -> [f64; 3] {
    let [kr, kg, kb] = Y_COEFF;
    let a = if n % 4 <= 1 { 0.0 } else { 100.0 };
    let b = if n.is_multiple_of(2) { 0.0 } else { 100.0 };
    let (v, axis) = if n < 4 {
        ([(y - kg * a - kb * b) / kr, a, b], 0)
    } else if n < 8 {
        ([b, (y - kr * b - kb * a) / kg, a], 1)
    } else {
        ([a, b, (y - kr * a - kg * b) / kb], 2)
    };
    if (0.0..=100.0).contains(&v[axis]) {
        v
    } else {
        [-1.0; 3]
    }
}
fn bisect_segment(y: f64, hue: f64) -> [[f64; 3]; 2] {
    let mut left = [-1.0; 3];
    let mut right = left;
    let mut lh = 0.0;
    let mut rh = 0.0;
    let mut initialized = false;
    let mut uncut = true;
    for n in 0..12 {
        let mid = vertex(y, n);
        if mid[0] < 0.0 {
            continue;
        }
        let mh = hue_of(mid);
        if !initialized {
            left = mid;
            right = mid;
            lh = mh;
            rh = mh;
            initialized = true;
            continue;
        }
        if uncut || cyclic(lh, mh, rh) {
            uncut = false;
            if cyclic(lh, hue, mh) {
                right = mid;
                rh = mh;
            } else {
                left = mid;
                lh = mh;
            }
        }
    }
    [left, right]
}
fn true_delinearized(c: f64) -> f64 {
    let c = c / 100.0;
    let v = if c <= 0.0031308 {
        c * 12.92
    } else {
        1.055 * c.powf(1.0 / 2.4) - 0.055
    };
    v * 255.0
}
fn bisect_limit(y: f64, hue: f64) -> [f64; 3] {
    let [mut left, mut right] = bisect_segment(y, hue);
    let mut lh = hue_of(left);
    for axis in 0..3 {
        if (left[axis] - right[axis]).abs() <= 1e-10 {
            continue;
        }
        let a = true_delinearized(left[axis]) - 0.5;
        let b = true_delinearized(right[axis]) - 0.5;
        let (mut lp, mut rp) = if left[axis] < right[axis] {
            (a.floor() as i32, b.ceil() as i32)
        } else {
            (a.ceil() as i32, b.floor() as i32)
        };
        for _ in 0..8 {
            if (rp - lp).abs() <= 1 {
                break;
            }
            let mp = ((lp + rp) / 2).clamp(0, 254);
            let coordinate = CRITICAL_PLANES[mp as usize];
            let t = (coordinate - left[axis]) / (right[axis] - left[axis]);
            let mid = std::array::from_fn(|i| left[i] + (right[i] - left[i]) * t);
            let mh = hue_of(mid);
            if cyclic(lh, hue, mh) {
                right = mid;
                rp = mp;
            } else {
                left = mid;
                lh = mh;
                lp = mp;
            }
        }
    }
    std::array::from_fn(|i| (left[i] + right[i]) / 2.0)
}
fn find_by_j(hue: f64, chroma: f64, y: f64) -> Option<Rgb> {
    let mut j = y.sqrt() * 11.0;
    let coeff = 1.0 / (1.64 - 0.29_f64.powf(N)).powf(0.73);
    let e = 0.25 * ((hue + 2.0).cos() + 3.8);
    let p1 = e * (50000.0 / 13.0) * NBB;
    let (sin, cos) = (hue.sin(), hue.cos());
    for iteration in 0..5 {
        let jn = j / 100.0;
        let alpha = if chroma == 0.0 || j == 0.0 {
            0.0
        } else {
            chroma / jn.sqrt()
        };
        let t = (alpha * coeff).powf(1.0 / 0.9);
        let ac = AW * jn.powf(1.0 / C / Z);
        let p2 = ac / NBB;
        let gamma = 23.0 * (p2 + 0.305) * t / (23.0 * p1 + 11.0 * t * cos + 108.0 * t * sin);
        let a = gamma * cos;
        let b = gamma * sin;
        let adapted = [
            (460.0 * p2 + 451.0 * a + 288.0 * b) / 1403.0,
            (460.0 * p2 - 891.0 * a - 261.0 * b) / 1403.0,
            (460.0 * p2 - 220.0 * a - 6300.0 * b) / 1403.0,
        ];
        let rgb = multiply(INVERSE_DISCOUNT, adapted.map(inverse_adapt));
        if rgb.iter().any(|v| *v < 0.0) {
            return None;
        }
        let fnj = Y_COEFF[0] * rgb[0] + Y_COEFF[1] * rgb[1] + Y_COEFF[2] * rgb[2];
        if fnj <= 0.0 {
            return None;
        }
        if iteration == 4 || (fnj - y).abs() < 0.002 {
            if rgb.iter().any(|v| *v > 100.01) {
                return None;
            }
            return Some(rgb.map(|c| delinearize(c / 100.0)));
        }
        j = j - (fnj - y) * j / (2.0 * fnj);
    }
    None
}
fn solve(hue: f64, chroma: f64, tone: f64) -> Rgb {
    let y = lstar_to_y(tone);
    if chroma < 0.0001 || tone < 0.0001 || tone > 99.9999 {
        return [delinearize(y / 100.0); 3];
    }
    let radians = hue.rem_euclid(360.0).to_radians();
    find_by_j(radians, chroma, y)
        .unwrap_or_else(|| bisect_limit(y, radians).map(|c| delinearize(c / 100.0)))
}

